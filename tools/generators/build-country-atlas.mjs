/**
 * Generates `apps/music-collection/src/app/data/user-location/country-atlas.ts`:
 * every country a collector can say they are in, with the point its pin sits
 * on. The names are not generated — they come from `Intl.DisplayNames` at
 * runtime, in the reader's own language.
 *
 * Source: the `world-countries` package (ISO 3166-1 with coordinates), read
 * only here, at generation time, so the app never carries it.
 *
 *   node tools/generators/build-country-atlas.mjs
 *
 * Run it again when the country list changes, and commit the result.
 */

import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const countries = require('world-countries');

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TARGET = join(
	ROOT,
	'apps/music-collection/src/app/data/user-location/country-atlas.ts'
);

const entries = countries
	.filter((country) => Array.isArray(country.latlng) && country.cca2)
	.map((country) => [country.cca2, country.latlng])
	.sort(([one], [other]) => one.localeCompare(other));

const lines = entries.map(([code, [latitude, longitude]]) => {
	// d3 projections take [longitude, latitude]; `world-countries` gives the
	// other order.
	return `\t${code}: [${longitude}, ${latitude}],`;
});

const source = `/**
 * Generated by \`tools/generators/build-country-atlas.mjs\` — do not edit.
 *
 * Where each country's pin sits, as [longitude, latitude], which is the
 * order d3 projections take. The names are not here: \`Intl.DisplayNames\`
 * gives them in the reader's language.
 */
export const COUNTRY_POSITIONS: Readonly<Record<string, [number, number]>> = {
${lines.join('\n')}
};
`;

await writeFile(TARGET, source, 'utf8');

console.log(`${entries.length} countries written to ${TARGET}`);
