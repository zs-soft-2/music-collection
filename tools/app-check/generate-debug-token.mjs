/**
 * Generates `apps/music-collection/src/environments/app-check-debug-token.ts`:
 * the App Check debug token the dev build starts with, so the callables
 * (`enforceAppCheck`) accept the calls from `nx serve`.
 *
 * The token is a secret — anyone holding it can call the dev callables past
 * App Check — so it never enters this (public) repository. It is created by
 * the tofu (`infra/modules/firebase`), lives in the state, and lands on the
 * machine in `.app-check-debug-token`, which git does not see:
 *
 *   tofu -chdir=infra/environments/dev output -raw app_check_debug_token \
 *     > .app-check-debug-token
 *
 * Sources, in order: the `MC_APP_CHECK_DEBUG_TOKEN` environment variable, then
 * that file. Without either, the generated token is empty and the app falls
 * back to the real reCAPTCHA — the way CI and every production build run.
 *
 * The file is generated (gitignored); the `app-check-token` Nx target runs
 * this before build, serve and test.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = join(ROOT, '.app-check-debug-token');
const TARGET = join(
	ROOT,
	'apps/music-collection/src/environments/app-check-debug-token.ts'
);

const token = (
	process.env.MC_APP_CHECK_DEBUG_TOKEN ||
	(await readFile(SOURCE, 'utf8').catch(() => ''))
).trim();

const source = `// Generated by tools/app-check/generate-debug-token.mjs — do not edit.
export const APP_CHECK_DEBUG_TOKEN = ${JSON.stringify(token)};
`;

// Only rewrite when the token changed, so the build cache survives.
const previous = await readFile(TARGET, 'utf8').catch(() => '');
if (previous !== source) {
	await writeFile(TARGET, source);
}

console.log(
	token
		? 'app check: debug token'
		: 'app check: real reCAPTCHA (no .app-check-debug-token)'
);
