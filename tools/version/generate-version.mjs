/**
 * Generates `apps/music-collection/src/environments/version.ts`: the build
 * suffix that the environments append to their own base version
 * (`1.0.0` → `1.0.0-build.42+abc1234`), so every deployed build gets its own
 * version:
 *
 *   build.<GITHUB_RUN_NUMBER>+<commit>   (CI)
 *   local+<commit>[.dirty]               (local)
 *
 * The file is generated (gitignored); the `version` Nx target runs this
 * before build, serve and test.
 *
 * It also writes `apps/music-collection/src/i18n-preload.js` (gitignored,
 * copied as an asset): the dictionary has to carry this version in its URL,
 * and the page asks for it before main.js has arrived — see below.
 */

import { execSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TARGET = join(
	ROOT,
	'apps/music-collection/src/environments/version.ts'
);
const PRELOAD_TARGET = join(ROOT, 'apps/music-collection/src/i18n-preload.js');
/** The version every build suffix is appended to. */
const BASE_VERSION = '1.0.0';

function git(command) {
	try {
		return execSync(`git ${command}`, { cwd: ROOT, encoding: 'utf8' }).trim();
	} catch {
		return '';
	}
}

const commit =
	process.env.GITHUB_SHA?.slice(0, 7) || git('rev-parse --short HEAD') || 'unknown';
const runNumber = process.env.GITHUB_RUN_NUMBER;
const dirty = !runNumber && git('status --porcelain') !== '';

const build = runNumber
	? `build.${runNumber}+${commit}`
	: `local+${commit}${dirty ? '.dirty' : ''}`;

const info = {
	version: `${BASE_VERSION}-${build}`,
	build,
	commit,
	buildTime: new Date().toISOString(),
};

const source = `// Generated by tools/version/generate-version.mjs — do not edit.
export const VERSION = ${JSON.stringify(info, null, '\t')} as const;
`;

// Only rewrite when the build changed, so the timestamp alone does not
// invalidate the build cache on every local run.
const previous = await readFile(TARGET, 'utf8').catch(() => '');
if (!previous.includes(`"version": ${JSON.stringify(info.version)}`)) {
	await writeFile(TARGET, source);
}

/*
 * The dictionary, asked for while main.js is still downloading.
 *
 * The app fetches it from an initializer (libs/core/i18n provide-i18n.ts),
 * which runs only once main.js has arrived and been executed, and the first
 * screen waits on it. On a slow phone that is a second of nothing, and it is
 * what Lighthouse measured as the late LCP. A preload started from the head
 * puts the download beside main.js instead; the loader's request then finds
 * it already there.
 *
 * The language is picked the way LanguageService picks it — the reader's
 * stored choice, the app default this browser last heard, the browser's own
 * languages, English — and English rides along whenever it is not the pick,
 * because Transloco loads the fallback dictionary with every other one. A
 * wrong guess costs one unused download, never a wrong screen: the app still
 * asks for what it actually needs.
 *
 * The URL must be the loader's to the byte (translation.loader.ts), or the
 * browser fetches the file twice. It is an external file rather than an
 * inline script so the CSP needs no new hash for it.
 */
const preload = `// Generated by tools/version/generate-version.mjs — do not edit.
(() => {
	const version = ${JSON.stringify(info.version)};
	const languages = ['hu', 'en', 'de'];
	const fallback = 'en';

	const known = (tag) => {
		const primary = String(tag ?? '').toLowerCase().split('-')[0];
		return languages.includes(primary) ? primary : null;
	};

	const pick = () => {
		try {
			const stored = JSON.parse(localStorage.getItem('mc-language') ?? 'null');
			if (known(stored?.language) === stored?.language && stored?.language) {
				return stored.language;
			}
			const handed = localStorage.getItem('mc-default-language');
			if (handed && known(handed) === handed) {
				return handed;
			}
		} catch {
			// Storage unavailable: the browser's own languages decide.
		}
		for (const tag of navigator.languages ?? []) {
			if (known(tag)) return known(tag);
		}
		return known(navigator.language) ?? fallback;
	};

	const preload = (language) => {
		const link = document.createElement('link');
		link.rel = 'preload';
		link.as = 'fetch';
		link.crossOrigin = 'anonymous';
		link.href =
			'assets/i18n/' + language + '.json?v=' + encodeURIComponent(version);
		document.head.appendChild(link);
	};

	const language = pick();
	preload(language);
	if (language !== fallback) preload(fallback);
})();
`;

const previousPreload = await readFile(PRELOAD_TARGET, 'utf8').catch(() => '');
if (previousPreload !== preload) {
	await writeFile(PRELOAD_TARGET, preload);
}

console.log(`build: ${build}`);
